// Bundles every SQL file into the migration Lambda (as a generated TypeScript
// module, so it works on any OS without copy steps), in the order the runner
// applies them: compat, the app's migrations, then AWS additions.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export function writeSqlBundle(repoRoot = join(__dirname, '..', '..')): string {
  const read = (dir: string, prefix: string, filter: (n: string) => boolean) =>
    readdirSync(dir)
      .filter((n) => n.endsWith('.sql') && filter(n))
      .sort()
      .map((n) => ({ name: `${prefix}/${n}`, sql: readFileSync(join(dir, n), 'utf8') }));
  const sqlDir = join(repoRoot, 'infra', 'sql');
  const files = [
    ...read(sqlDir, 'compat', (n) => n.startsWith('0')),
    ...read(join(repoRoot, 'supabase', 'migrations'), 'app', () => true),
    ...read(sqlDir, 'aws', (n) => n.startsWith('9')),
  ];
  const outFile = join(repoRoot, 'infra', 'lambda', 'migrate', 'sql.generated.ts');
  writeFileSync(
    outFile,
    `// Generated by infra/lib/sql-bundle.ts. Do not edit.\n` +
      `import type { SqlFile } from './runner';\n\n` +
      `export const SQL_FILES: SqlFile[] = ${JSON.stringify(files, null, 2)};\n`,
  );
  return outFile;
}

if (require.main === module) {
  console.log(`Wrote ${writeSqlBundle()}`);
}
